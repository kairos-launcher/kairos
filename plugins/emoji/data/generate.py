#!/usr/bin/env python3
"""Build emoji.tsv from Unicode's emoji-test.txt and CLDR's English annotations.

    curl -LO https://unicode.org/Public/emoji/latest/emoji-test.txt
    curl -LO https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-annotations-full/annotations/en/annotations.json
    python3 generate.py emoji-test.txt annotations.json > emoji.tsv

One line per emoji (skin-tone variants folded into their base):
    emoji <TAB> name <TAB> group <TAB> keywords (|-separated) <TAB> 5 skin-tone variants (space-separated, or empty)
Data: Unicode, Inc., under the Unicode License v3 (https://www.unicode.org/license.txt).
"""
import json
import sys

TONES = ["light skin tone", "medium-light skin tone", "medium skin tone", "medium-dark skin tone", "dark skin tone"]


def main(test_path, ann_path):
    ann = json.load(open(ann_path, encoding="utf-8"))["annotations"]["annotations"]
    entries, by_name, group = [], {}, ""
    version = ""
    for line in open(test_path, encoding="utf-8"):
        if line.startswith("# Version:"):
            version = line.split(":", 1)[1].strip()
        if line.startswith("# group:"):
            group = line.split(":", 1)[1].strip()
            continue
        if not line.strip() or line.startswith("#") or "; fully-qualified" not in line:
            continue
        comment = line.split("#", 1)[1].strip()
        emoji, _, rest = comment.partition(" ")
        name = rest.split(" ", 1)[1].strip()  # drop the "E15.0" version
        by_name[name] = emoji
        entries.append((emoji, name, group))

    def cldr(e):
        return ann.get(e) or ann.get(e.replace("️", "")) or {}

    print(f"# Emoji {version}; generated by generate.py from Unicode emoji-test.txt and CLDR annotations (Unicode License v3)")
    for emoji, name, grp in entries:
        if any(f": {t}" in name or f", {t}" in name for t in TONES):
            continue  # a skin-tone variant: listed with its base
        a = cldr(emoji)
        keywords = [k for k in a.get("default", []) if k.lower() != name.lower()]
        tones = [by_name.get(f"{name}: {t}") for t in TONES]
        variants = " ".join(tones) if all(tones) else ""
        print("\t".join([emoji, name, grp, "|".join(keywords), variants]))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
