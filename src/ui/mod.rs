/// A search that takes longer than this shows the progress bar; an action, the spinner.
const SEARCH_CUE_DELAY: Duration = Duration::from_millis(150);
/// After a drag ends without focus coming back: wait this long before asking for it, and as long
/// again before treating it as a real focus loss.
const REFOCUS_DELAY: Duration = Duration::from_millis(400);

/// Set by [`quit_then`]: what to start once this instance has let go of its control socket.
static AFTER_QUIT: Mutex<Option<Vec<String>>> = Mutex::new(None);
/// Set on the instance started by [`quit_then`], which may still be exiting.
const RESTARTED_ENV: &str = "KAIROS_RESTARTED";

/// Quit, then start `argv` (with `RESTARTED_ENV` set). Used by the updater to restart.
#[cfg_attr(not(feature = "remote"), allow(dead_code))]
pub fn quit_then(argv: Vec<String>) {
    *lock(&AFTER_QUIT) = Some(argv);
    let _ = slint::quit_event_loop();
}

/// Claim the control socket. An instance started by [`quit_then`] waits for the old one to
/// let go (on Windows a pipe lives until its process has exited).
fn bind_control_socket() -> std::io::Result<Option<ipc::Server>> {
    let restarted = std::env::var_os(RESTARTED_ENV).is_some();
    for _ in 0..50 {
        match ipc::bind()? {
            None if restarted => std::thread::sleep(Duration::from_millis(100)),
            other => return Ok(other),
        }
    }
    ipc::bind()
}

/// Run the resident launcher until it is told to quit.
pub fn run(cfg: &Config, background: bool) -> Result<(), String> {
    // Single instance; the socket also carries `--toggle` from desktop shortcuts.
    let Some(server) = bind_control_socket().map_err(|e| format!("cannot create control socket: {e}"))? else {
        log::info!("launcher is already running");
        // Started again by the user (Start menu, double-click): open the running one. A second
        // autostart stays quiet.
        if !background {
            ipc::send(&ipc::Request::new(ipc::Command::Show))
                .map_err(|e| format!("cannot reach the running launcher: {e}"))?;
        }
        return Ok(());
    };

    let engine = Engine::new(cfg);
    {
        let engine = engine.clone();
        std::thread::spawn(move || {
            // Show each plugin's settings (commented out, at their defaults) in config.toml.
            engine.write_default_sections();
            engine.warm_up();
            // Started hidden (autostart): give startup memory back, as after a hide.
            if background {
                engine.schedule_reap();
            }
        });
    }

    slint::BackendSelector::new()
        .backend_name("winit".into())
        .renderer_name("software".into())
        .with_winit_window_attributes_hook(|attrs| match with_state(|s| s.activation_token.take()) {
            Some(token) => with_activation_token(attrs, token),
            None => attrs,
        })
        .select()
        .map_err(|e| format!("cannot start the UI backend: {e}"))?;
    let ui = MainWindow::new().map_err(|e| format!("cannot create the window: {e}"))?;
    ui.set_app_icon(window_icon());
    ui.global::<Theme>().set_mode(theme_mode_index(cfg.theme));
    if cfg!(windows) {
        ui.global::<Theme>().set_corner_radius(0.0);
    }
    with_state(|s| {
        s.placement = cfg.position;
        s.animations = cfg.animations;
        // Set by the desktop when it launched us; lets Wayland compositors focus the window.
        s.activation_token = std::env::var("XDG_ACTIVATION_TOKEN").ok().filter(|v| !v.is_empty());
    });

    let app = App { weak: ui.as_weak(), engine, shared: Arc::default() };
    app.refresh_system_theme();
    app.wire_callbacks(&ui);

    // Global hotkey. Wayland forbids app-level key grabs; there the control socket is the
    // trigger (`kairos --install-shortcut` binds it in the desktop). The manager must stay
    // alive for the whole run.
    let hotkey = if is_wayland() {
        log::info!("Wayland: bind `kairos --toggle` to {} (see `kairos --install-shortcut`).", cfg.hotkey);
        None
    } else {
        register_hotkey(&cfg.hotkey)
    };
    if let Some((_, id)) = &hotkey {
        app.listen_for_hotkey(*id);
    }

    {
        let app = app.clone();
        if let Err(e) = server.serve(move |req| app.post_request(req)) {
            log::error!("control socket: {e}");
        }
    }

    if cfg.tray {
        app.spawn_tray();
    }

    if background {
        app.prepare_hidden_window();
    } else {
        app.post(Command::Show, None);
    }

    let result = slint::run_event_loop_until_quit().map_err(|e| format!("event loop: {e}"));
    drop(hotkey);
    drop(server); // removes the socket file
    if let Some(argv) = lock(&AFTER_QUIT).take() {
        log::info!("starting {argv:?}");
        crate::core::process::spawn_env(&argv, &[(RESTARTED_ENV, "1")])?;
    }
    result
}

/// State that only the UI thread touches.
#[derive(Default)]
struct UiState {
    /// xdg-activation token from the shortcut that asked for the window; consumed when the
    /// window is created so the compositor grants it keyboard focus (Wayland).
    activation_token: Option<String>,
    /// Which monitor to open on (`position` in config.toml).
    placement: Placement,
    animations: bool,
    /// True from the moment the user starts dragging until the next show, so only user drags
    /// (not our own centring) are remembered as the window position.
    dragging: bool,
    /// Where the user last dragged the window, as an offset from the top-left of its monitor,
    /// so it lands at the same spot on whichever monitor it opens on.
    user_offset: Option<(i32, i32)>,
    drag: DragGuard,
    /// Whether the window has keyboard focus, as last reported by the system.
    focused: bool,
    /// Keys of the rows in `model`, in order, so a re-published list can keep the selection.
    shown_keys: Vec<String>,
    /// The one model behind the list: updated in place, so rows that stay are not rebuilt.
    model: Rc<VecModel<Item>>,
    icons: rows::IconCache,
    fresh_timer: Rc<slint::Timer>,
    search_timer: Rc<slint::Timer>,
    busy_timer: Rc<slint::Timer>,
    /// The output panel, while it is open.
    output: Option<output::OutputView>,
    /// A plugin's settings page, while it is open.
    settings: Option<settings::SettingsView>,
    /// An unfinished search to bring back if the launcher reopens soon (`keep_search_s`).
    resume: Option<Resume>,
    /// Drops `resume` (and an open answer panel) once it is too old.
    resume_timer: Rc<slint::Timer>,
    output_timers: output::OutputTimers,
    /// Keeps the tray icon alive on the UI thread (Windows requires it to stay there).
    tray: Option<tray::TrayHandle>,
}

/// What was on screen when the launcher closed without running anything.
struct Resume {
    query: String,
    hidden_at: Instant,
}

/// Whether a search left at `hidden_at` is still worth bringing back at `now`.
fn resumable(hidden_at: Instant, now: Instant, keep: Duration) -> bool {
    !keep.is_zero() && now.saturating_duration_since(hidden_at) <= keep
}

thread_local! {
    static STATE: RefCell<UiState> = RefCell::default();
}

/// Access the UI thread's state. Keep the closure short and never change the window from it:
/// Slint may run our callbacks synchronously, and those take the state again.
fn with_state<R>(f: impl FnOnce(&mut UiState) -> R) -> R {
    STATE.with_borrow_mut(f)
}

/// What worker threads share with the UI.
#[derive(Default)]
struct Shared {
    /// The results on screen, in order, so Enter acts on what is shown.
    results: Mutex<Vec<ResultItem>>,
    /// Id of the newest query; older ones stop publishing.
    latest: AtomicU64,
    /// Query the progress bar waits for (0: none).
    pending: AtomicU64,
    /// An action is running; further activations are ignored meanwhile.
    executing: AtomicBool,
    /// Id of the newest execution (`exec` in the protocol).
    next_exec: AtomicU64,
    /// Output events on their way to the panel.
    output: Mutex<output::Inbox>,
}

/// A cheap handle to everything the callbacks need. Clone it into closures.
#[derive(Clone)]
struct App {
    weak: slint::Weak<MainWindow>,
    engine: Arc<Engine>,
    shared: Arc<Shared>,
}

impl App {
    fn wire_callbacks(&self, ui: &MainWindow) {
        let app = self.clone();
        ui.on_query_changed(move |text| app.search(text.to_string()));
        let app = self.clone();
        ui.on_activate(move |row| app.activate(row, None));
        let app = self.clone();
        ui.on_run_action(move |row, action| app.activate(row, Some(action)));
        let app = self.clone();
        ui.on_open_menu(move |row| app.open_menu(row));
        let app = self.clone();
        ui.on_output_action(move |i| app.run_output_action(i));
        let app = self.clone();
        ui.on_output_menu(move || app.open_output_menu());
        let app = self.clone();
        ui.on_output_back(move || app.close_output());
        let app = self.clone();
        ui.on_output_stop(move || app.stop_output());
        let app = self.clone();
        ui.on_output_link(move |url| app.open_output_link(&url));
        let app = self.clone();
        ui.on_output_send(move |text| app.send_output_input(&text));
        let app = self.clone();
        ui.on_settings_edited(move |i, text| app.settings_edited(i, &text));
        let app = self.clone();
        ui.on_settings_reset(move |i| app.settings_reset(i));
        let app = self.clone();
        ui.on_settings_item_add(move |i, name, value| app.settings_item_add(i, &name, &value));
        let app = self.clone();
        ui.on_settings_item_remove(move |i, name| app.settings_item_remove(i, &name));
        let app = self.clone();
        ui.on_settings_entry_open(move |i, name| app.settings_entry_open(i, &name));
        let app = self.clone();
        ui.on_settings_open_config(move || app.settings_open_config());
        let app = self.clone();
        ui.on_settings_save(move || app.save_settings());
        let app = self.clone();
        ui.on_settings_back(move || app.settings_back());
        let app = self.clone();
        ui.on_start_drag(move || app.start_drag());
        let app = self.clone();
        ui.on_dismiss(move || app.hide());
        let app = self.clone();
        ui.window().on_winit_window_event(move |window, ev| {
            app.on_window_event(window, ev);
            EventResult::Propagate
        });
    }

    /// Run `cmd` on the UI thread. Callable from any thread.
    fn post(&self, cmd: Command, token: Option<String>) {
        self.post_request(ipc::Request { token, ..ipc::Request::new(cmd) });
    }

    /// Run a control-socket request on the UI thread. Callable from any thread.
    fn post_request(&self, req: ipc::Request) {
        let app = self.clone();
        let _ = slint::invoke_from_event_loop(move || app.handle(req));
    }

    fn handle(&self, req: ipc::Request) {
        let Some(ui) = self.weak.upgrade() else { return };
        let visible = ui.window().is_visible();
        let ipc::Request { cmd, token, query } = req;
        match cmd {
            // With search text the launcher opens (or stays open) on that search.
            Command::Toggle if visible && query.is_none() => self.hide(),
            Command::Toggle | Command::Show if !visible => {
                if token.is_some() {
                    with_state(|s| s.activation_token = token);
                }
                self.show();
                if let Some(q) = query {
                    self.open_with_query(q);
                }
            }
            Command::Toggle | Command::Show => {
                if let Some(q) = query {
                    self.open_with_query(q);
                }
            }
            Command::Hide => self.hide(),
            Command::Quit => {
                let _ = slint::quit_event_loop();
            }
        }
    }

    fn show(&self) {
        let Some(ui) = self.weak.upgrade() else { return };
        let placement = with_state(|s| {
            s.dragging = false;
            s.placement
        });
        self.refresh_system_theme();
        self.engine.cancel_reap();
        let keep = self.engine.keep_search();
        let resume = with_state(|s| {
            s.resume_timer.stop();
            s.resume.take()
        })
        .filter(|r| resumable(r.hidden_at, Instant::now(), keep));
        ui.set_menu_open(false);
        ui.set_busy(self.shared.executing.load(Ordering::SeqCst));
        // Closed without running anything, a moment ago: come back to the same place.
        let research = match resume {
            // The answer panel or the settings page, as it was.
            Some(_) if ui.get_output_open() || ui.get_settings_open() => None,
            Some(r) if !r.query.is_empty() => {
                ui.set_query(r.query.clone().into());
                ui.set_selected(0);
                ui.set_items(ModelRc::default());
                Some(r.query)
            }
            _ => {
                self.close_output();
                self.close_settings();
                ui.set_query(SharedString::new());
                ui.set_selected(0);
                ui.set_items(ModelRc::default());
                None
            }
        };
        // Before showing: once we are up, we are the active window.
        let anchor = if is_wayland() { None } else { screen::anchor_point(placement) };
        let _ = ui.show();
        if !is_wayland() {
            let offset = with_state(|s| s.user_offset);
            placement::move_to_monitor(&ui, anchor, offset);
        }
        // Windows only lets a background process take the foreground when it forces it; a plain
        // show leaves the keyboard with the previous app.
        if cfg!(windows) {
            ui.window().with_winit_window(winit::window::Window::focus_window);
        }
        ui.invoke_focus_input();
        if let Some(query) = research {
            // Fresh results for the old query, which is selected so typing replaces it.
            self.search(query);
            ui.invoke_select_all();
        }
        let engine = self.engine.clone();
        std::thread::spawn(move || {
            // Edits to config.toml (by hand or from the plugin manager) apply on the next show.
            engine.reload_if_config_changed();
            engine.refresh_if_stale();
        });
    }

    /// Close without having run anything (Esc, focus lost, hotkey): the search is kept for a
    /// moment in case the launcher reopens (`keep_search_s`).
    fn hide(&self) {
        self.hide_with(false);
    }

    /// Close because an action ran: the next open starts empty.
    fn hide_done(&self) {
        self.hide_with(true);
    }

    fn hide_with(&self, finished: bool) {
        let Some(ui) = self.weak.upgrade() else { return };
        if !ui.window().is_visible() {
            return;
        }
        let keep = self.engine.keep_search();
        if finished || keep.is_zero() {
            with_state(|s| {
                s.resume = None;
                s.resume_timer.stop();
            });
            self.close_output();
            self.close_settings();
        } else {
            // An open answer panel keeps streaming meanwhile; it is dropped with `resume`.
            let query = ui.get_query().to_string();
            with_state(|s| s.resume = Some(Resume { query, hidden_at: Instant::now() }));
            let app = self.clone();
            let timer = with_state(|s| s.resume_timer.clone());
            timer.start(slint::TimerMode::SingleShot, keep, move || app.drop_resume());
        }
        let _ = ui.hide();
        // Decoded icons are cheap to decode again and would otherwise stay while hidden.
        with_state(|s| s.icons = rows::IconCache::default());
        self.engine.schedule_reap();
    }

    /// The kept search is too old now: forget it, and stop and free an answer panel.
    fn drop_resume(&self) {
        let Some(ui) = self.weak.upgrade() else { return };
        if ui.window().is_visible() {
            return;
        }
        with_state(|s| s.resume = None);
        self.close_output();
        self.close_settings();
        ui.set_query(SharedString::new());
    }

    /// `kairos --query <text>`: search for `text` as if it had been typed.
    fn open_with_query(&self, text: String) {
        let Some(ui) = self.weak.upgrade() else { return };
        ui.set_menu_open(false);
        self.close_output();
        self.close_settings();
        ui.set_query(text.as_str().into());
        ui.set_selected(0);
        ui.set_items(ModelRc::default());
        self.search(text);
    }

    /// Typing: query on a worker thread and drop stale answers. Lazy plugin icons arrive in a
    /// second step so a slow icon never delays the results themselves.
    fn search(&self, text: String) {
        let qid = self.shared.latest.fetch_add(1, Ordering::SeqCst) + 1;
        if with_state(|s| s.animations) {
            self.start_progress_cue(qid);
        }
        let app = self.clone();
        std::thread::spawn(move || {
            let shared = &app.shared;
            let current = || shared.latest.load(Ordering::SeqCst) == qid;
            let mut found = vec![];
            let mut shown = false;
            app.engine.query_stream(&text, |items| {
                if !current() {
                    return false;
                }
                found.clone_from(&items);
                app.publish(items, std::mem::replace(&mut shown, true));
                true
            });
            if shared.pending.compare_exchange(qid, 0, Ordering::SeqCst, Ordering::SeqCst).is_ok() {
                app.set_searching_later(false);
            }
            if current() && app.engine.fetch_lazy_icons(&mut found) && current() {
                app.publish(found, true);
            }
        });
    }

    /// Show the progress bar if query `qid` is still running after `SEARCH_CUE_DELAY`.
    fn start_progress_cue(&self, qid: u64) {
        self.shared.pending.store(qid, Ordering::SeqCst);
        if let Some(ui) = self.weak.upgrade() {
            ui.set_searching(false);
        }
        let app = self.clone();
        let timer = with_state(|s| s.search_timer.clone());
        timer.start(slint::TimerMode::SingleShot, SEARCH_CUE_DELAY, move || {
            if let Some(ui) = app.weak.upgrade() {
                ui.set_searching(app.shared.pending.load(Ordering::SeqCst) == qid);
            }
        });
    }

    fn set_searching_later(&self, on: bool) {
        let weak = self.weak.clone();
        let _ = slint::invoke_from_event_loop(move || {
            if let Some(ui) = weak.upgrade() {
                ui.set_searching(on);
            }
        });
    }

    /// Make `items` the current results and show them. Callable from any thread; rows are built
    /// on the UI thread because `slint::Image` is not `Send`.
    ///
    /// With `follow`, the list is an update of the one on screen (late provider results, lazy
    /// icons): the selected result stays selected wherever it now ranks. A new query starts at
    /// the top, and an untouched cursor (row 0) stays on the top result, which a late provider
    /// may well own. Rows that first appear in an update fade in.
    fn publish(&self, items: Vec<ResultItem>, follow: bool) {
        let app = self.clone();
        let _ = slint::invoke_from_event_loop(move || app.show_results(items, follow));
    }

    fn show_results(&self, items: Vec<ResultItem>, follow: bool) {
        let Some(ui) = self.weak.upgrade() else { return };
        let keys: Vec<String> = items.iter().map(engine::key).collect();
        let cursor = usize::try_from(ui.get_selected()).unwrap_or(0);
        let (rows, model, mut shown, fade) = with_state(|s| {
            let rows: Vec<Item> = items.iter().map(|r| rows::to_item(r, &mut s.icons)).collect();
            (rows, s.model.clone(), std::mem::take(&mut s.shown_keys), follow && s.animations)
        });
        // Only a row the user moved to is followed.
        let selected = shown.get(cursor).cloned().filter(|_| cursor > 0);
        // The shared list changes together with the model, so Enter acts on what is shown.
        *lock(&self.shared.results) = items;
        model_sync::sync_model(&model, &mut shown, &keys, rows, fade);
        // Something else (a reset on show) may have replaced the bound model; bind ours again.
        let bound = ui
            .get_items()
            .as_any()
            .downcast_ref::<VecModel<Item>>()
            .is_some_and(|m| std::ptr::eq(m, Rc::as_ptr(&model)));
        if !bound {
            ui.set_items(ModelRc::from(model.clone()));
        }
        if follow {
            ui.set_selected(i32::try_from(model_sync::followed_index(selected, &keys)).unwrap_or(0));
        }
        with_state(|s| s.shown_keys = shown);
        if fade && model.iter().any(|r| r.fresh) {
            // Next tick: clearing the flag is what makes the rows fade in from transparent.
            let timer = with_state(|s| s.fresh_timer.clone());
            timer.start(slint::TimerMode::SingleShot, Duration::from_millis(20), move || {
                for i in 0..model.row_count() {
                    if let Some(mut r) = model.row_data(i).filter(|r| r.fresh) {
                        r.fresh = false;
                        model.set_row_data(i, r);
                    }
                }
            });
        }
    }

    /// Run an action (an index into the result's actions, or its default) on result `row`. The
    /// action runs off the UI thread (it may install a plugin or wait on a slow external one);
    /// its outcome is applied back on the UI thread.
    fn activate(&self, row: i32, action: Option<i32>) {
        let Some(item) = usize::try_from(row).ok().and_then(|i| lock(&self.shared.results).get(i).cloned()) else {
            return;
        };
        let action = match action {
            Some(a) => usize::try_from(a).ok().and_then(|a| item.actions.get(a)),
            None => item.default_action(),
        };
        let Some(action) = action.cloned() else { return };
        self.run(item, action);
    }

    /// Run `action` of `item`. An action marked `output` (or any action started from the output
    /// panel) shows the panel at once; others show the spinner if they take a while.
    fn run(&self, item: ResultItem, action: Action) {
        self.run_with_input(item, action, None);
    }

    /// `run`, with text typed into the output panel's input. False if another action is still
    /// starting (nothing ran).
    fn run_with_input(&self, item: ResultItem, action: Action, input: Option<String>) -> bool {
        let Some(ui) = self.weak.upgrade() else { return false };
        if self.shared.executing.swap(true, Ordering::SeqCst) {
            return false;
        }
        let exec = self.shared.next_exec.fetch_add(1, Ordering::SeqCst) + 1;
        self.expect_output(exec);
        if action.output || ui.get_output_open() {
            self.open_output(&ui, &item, exec);
        } else {
            self.start_busy_cue();
        }
        let ctx = ExecCtx { exec, sink: self.output_sink(exec), input };
        let app = self.clone();
        std::thread::spawn(move || {
            let out = app.engine.execute(&item, &action.id, &ctx);
            let shared = app.shared.clone();
            let posted = slint::invoke_from_event_loop(move || {
                app.shared.executing.store(false, Ordering::SeqCst);
                with_state(|s| s.busy_timer.clone()).stop();
                let Some(ui) = app.weak.upgrade() else { return };
                ui.set_busy(false);
                match out {
                    Ok(ExecOutcome::Output(start)) => app.apply_output_start(&ui, &item, exec, *start),
                    Ok(ExecOutcome::Settings(id)) => {
                        app.output_not_needed(exec);
                        app.close_output();
                        app.open_settings(&ui, &id);
                    }
                    Ok(out) => {
                        app.output_not_needed(exec);
                        if let Some(text) = out.query() {
                            complete_search(&ui, text);
                        }
                        ui.set_menu_open(false);
                        if !out.keeps_open() {
                            app.hide_done();
                        }
                    }
                    Err(e) => {
                        log::warn!("execute failed: {e}");
                        // Without a panel for this run the failure would go unseen: open one.
                        let message = e.to_string();
                        if !app.output_failed(exec, &message) {
                            app.open_output(&ui, &item, exec);
                            app.output_failed(exec, &message);
                        }
                    }
                }
            });
            if posted.is_err() {
                shared.executing.store(false, Ordering::SeqCst);
            }
        });
        true
    }

    /// An action still running after `SEARCH_CUE_DELAY` hides the list and shows the spinner.
    /// Quick ones (launching an app) finish before that and never flash it.
    fn start_busy_cue(&self) {
        let app = self.clone();
        let timer = with_state(|s| s.busy_timer.clone());
        timer.start(slint::TimerMode::SingleShot, SEARCH_CUE_DELAY, move || {
            if !app.shared.executing.load(Ordering::SeqCst) {
                return;
            }
            if let Some(ui) = app.weak.upgrade() {
                ui.set_menu_open(false);
                ui.set_busy(true);
            }
        });
    }

    /// Tab: the result decides what it means. Autocomplete if it carries `complete` (e.g. a
    /// suggested command), otherwise the actions menu.
    fn open_menu(&self, row: i32) {
        let Some(ui) = self.weak.upgrade() else { return };
        let Some(item) = usize::try_from(row).ok().and_then(|i| lock(&self.shared.results).get(i).cloned()) else {
            return;
        };
        if let Some(text) = &item.complete {
            complete_search(&ui, text);
            return;
        }
        if item.actions.is_empty() {
            return; // nothing to choose from (e.g. an error result)
        }
        let default = item.default_action().map(|d| d.id.as_str());
        let actions: Vec<ActionItem> = item
            .actions
            .iter()
            .map(|a| ActionItem { title: a.title.clone().into(), is_default: Some(a.id.as_str()) == default })
            .collect();
        ui.set_actions(ModelRc::new(VecModel::from(actions)));
        ui.set_action_selected(0);
        ui.set_menu_open(true);
    }

    fn start_drag(&self) {
        let Some(ui) = self.weak.upgrade() else { return };
        with_state(|s| {
            s.dragging = true;
            s.drag.start(Instant::now());
        });
        // The compositor/OS runs the move; works on Wayland, X11 and Windows.
        ui.window().with_winit_window(|w| {
            let _ = w.drag_window();
        });
    }

    /// Hide when the window loses focus, except when our own drag caused it.
    fn on_window_event(&self, window: &slint::Window, ev: &winit::event::WindowEvent) {
        use winit::event::{ElementState, WindowEvent as W};
        match ev {
            W::Focused(true) => {
                with_state(|s| {
                    s.focused = true;
                    s.drag.end();
                });
                log::debug!("focus: true");
            }
            W::Focused(false) => {
                let dragging = with_state(|s| {
                    s.focused = false;
                    s.drag.active(Instant::now())
                });
                log::debug!("focus: false{}", if dragging { " (ignored: window drag in progress)" } else { "" });
                if !dragging {
                    self.hide();
                }
            }
            // The pointer coming back after a Wayland move grab means the drag is over. If the
            // compositor has not given focus back by then, ask for it once, then treat it as a
            // real focus loss.
            W::CursorEntered { .. } if with_state(|s| s.drag.active(Instant::now())) => {
                let focused = with_state(|s| {
                    s.drag.end();
                    s.focused
                });
                if !focused {
                    self.recover_focus_after_drag();
                }
            }
            // X11/Windows deliver the button release after the move; Wayland does not.
            W::MouseInput { state: ElementState::Released, .. } => with_state(|s| s.drag.end()),
            W::Moved(pos) if with_state(|s| s.dragging) => {
                let origin = window.with_winit_window(|w| w.current_monitor().map(|m| m.position())).flatten();
                let (ox, oy) = origin.map_or((0, 0), |o| (o.x, o.y));
                with_state(|s| s.user_offset = Some((pos.x - ox, pos.y - oy)));
            }
            _ => {}
        }
    }

    fn recover_focus_after_drag(&self) {
        let app = self.clone();
        slint::Timer::single_shot(REFOCUS_DELAY, move || {
            let Some(ui) = app.weak.upgrade() else { return };
            if with_state(|s| s.focused) || !ui.window().is_visible() {
                return;
            }
            log::debug!("drag ended without focus: requesting it");
            ui.window().with_winit_window(winit::window::Window::focus_window);
            slint::Timer::single_shot(REFOCUS_DELAY, move || {
                if !with_state(|s| s.focused) {
                    app.hide();
                }
            });
        });
    }

    /// The hotkey thread blocks on the channel: no polling while idle.
    fn listen_for_hotkey(&self, id: u32) {
        let app = self.clone();
        std::thread::spawn(move || {
            let rx = GlobalHotKeyEvent::receiver();
            while let Ok(ev) = rx.recv() {
                if ev.id == id && ev.state == HotKeyState::Pressed {
                    app.post(Command::Toggle, None);
                }
            }
        });
    }

    /// Created from inside the event loop: on Windows the tray belongs to the thread that
    /// pumps messages.
    fn spawn_tray(&self) {
        let app = self.clone();
        let _ = slint::invoke_from_event_loop(move || {
            let handle = tray::spawn(move |cmd| match cmd {
                tray::TrayCommand::Show => app.post(Command::Show, None),
                tray::TrayCommand::Quit => app.post(Command::Quit, None),
                tray::TrayCommand::Settings => {
                    if let Err(e) = config::open_config() {
                        log::warn!("settings: {e}");
                    }
                }
            });
            with_state(|s| s.tray = handle);
        });
    }

    /// Started hidden. Slint creates the native window hidden when the event loop starts, and
    /// Wayland cannot un-hide a window created that way (winit's `set_visible` is a no-op
    /// there): the first real `show()` would never map. A show+hide once the loop is up makes
    /// Slint destroy that window, so every later `show()` creates a fresh visible one. Nothing
    /// is drawn: both calls run in the same turn, before any frame.
    fn prepare_hidden_window(&self) {
        let weak = self.weak.clone();
        let _ = slint::invoke_from_event_loop(move || {
            slint::Timer::single_shot(Duration::from_millis(300), move || {
                if let Some(ui) = weak.upgrade() {
                    let _ = ui.show();
                    let _ = ui.hide();
                }
            });
        });
    }

    /// Follow the desktop's dark/light setting (for `theme = "auto"`). Checked on a worker
    /// thread because it asks `gsettings` / the registry.
    fn refresh_system_theme(&self) {
        let weak = self.weak.clone();
        std::thread::spawn(move || {
            let Some(dark) = theme::system_prefers_dark() else { return };
            let _ = slint::invoke_from_event_loop(move || {
                if let Some(ui) = weak.upgrade() {
                    ui.global::<Theme>().set_system_dark(dark);
                }
            });
        });
    }
}

/// Put `text` in the search box (cursor at the end) and run the search for it.
fn complete_search(ui: &MainWindow, text: &str) {
    ui.invoke_complete(text.into());
    ui.invoke_query_changed(text.into());
}

/// `Theme.mode` in `ui/main.slint`: 0 follows the system, 1 dark, 2 light.
fn theme_mode_index(mode: ThemeMode) -> i32 {
    match mode {
        ThemeMode::Auto => 0,
        ThemeMode::Dark => 1,
        ThemeMode::Light => 2,
    }
}

/// Wayland/X11 only: lets the compositor give the new window keyboard focus.
#[cfg(all(unix, not(target_os = "macos")))]
fn with_activation_token(attrs: winit::window::WindowAttributes, token: String) -> winit::window::WindowAttributes {
    attrs.with_activation_token(winit::window::ActivationToken::from_raw(token))
}

#[cfg(not(all(unix, not(target_os = "macos"))))]
fn with_activation_token(attrs: winit::window::WindowAttributes, _token: String) -> winit::window::WindowAttributes {
    attrs
}

fn is_wayland() -> bool {
    cfg!(unix) && std::env::var_os("WAYLAND_DISPLAY").is_some()
}

fn register_hotkey(spec: &str) -> Option<(GlobalHotKeyManager, u32)> {
    let hotkey: HotKey = match spec.parse() {
        Ok(h) => h,
        Err(e) => {
            log::warn!("invalid hotkey {spec:?}: {e}");
            return None;
        }
    };
    let manager = GlobalHotKeyManager::new().ok()?;
    if let Err(e) = manager.register(hotkey) {
        log::warn!("cannot grab {spec:?} (another app may own it): {e}; `kairos --toggle` still works.");
        return None;
    }
    Some((manager, hotkey.id()))
}

/// The taskbar / alt-tab icon. 48 px is plenty there and keeps it to 9 KB of pixels.
fn window_icon() -> slint::Image {
    const SIZE: u32 = 48;
    let px =
        slint::SharedPixelBuffer::<slint::Rgba8Pixel>::clone_from_slice(&crate::app_icon::icon_rgba(SIZE), SIZE, SIZE);
    slint::Image::from_rgba8(px)
}
